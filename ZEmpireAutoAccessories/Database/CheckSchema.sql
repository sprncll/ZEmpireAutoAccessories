/* ---- 1. columns the app needs that are not here --------------------- */
SELECT
    e.SchemaName,
    e.TableName,
    e.ColumnName,
    CASE WHEN OBJECT_ID(QUOTENAME(e.SchemaName) + '.' + QUOTENAME(e.TableName)) IS NULL
         THEN 'THE WHOLE TABLE IS MISSING'
         ELSE 'column missing' END AS Problem
FROM @Expected e
LEFT JOIN sys.columns c
       ON c.object_id = OBJECT_ID(QUOTENAME(e.SchemaName) + '.' + QUOTENAME(e.TableName))
      AND c.name = e.ColumnName
WHERE c.column_id IS NULL
ORDER BY e.SchemaName, e.TableName, e.ColumnName;

/* ---- 2. and the count, so "nothing" is a visible answer ------------- */
SELECT COUNT(*) AS MissingColumns
FROM @Expected e
LEFT JOIN sys.columns c
       ON c.object_id = OBJECT_ID(QUOTENAME(e.SchemaName) + '.' + QUOTENAME(e.TableName))
      AND c.name = e.ColumnName
WHERE c.column_id IS NULL;
